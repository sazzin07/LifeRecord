def normalize(code: Optional[str]) -> str:
    """`usd` -> `USD`. Raises ValueError for anything that is not in the list."""
    c = (code or "").strip().upper()
    if c not in CURRENCIES:
        raise ValueError(f"{code!r} is not a currency this app knows")
    return c


def is_currency(code: Optional[str]) -> bool:
    return (code or "").strip().upper() in CURRENCIES


def currency_digits(code: str) -> int:
    return CURRENCIES[normalize(code)]["digits"]
